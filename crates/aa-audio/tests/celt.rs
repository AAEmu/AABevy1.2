//! Real legacy CELT evidence. No PCM is embedded: the native reference is generated locally
//! by tools/native_celt_oracle.py from the original hash-pinned DLL and bank.

use std::{path::PathBuf, time::Instant};

use aa_audio::library::{PickState, Rng, active_instances, initial_values, layer_gain, plan};
use aa_audio::{Fsb5, Library, decode, fsb5::Codec};

const BANK: &str = "sounds/x2weapons_sword/x2weapons_sword_bank055.fsb";
const EVENT: &str = "sounds/x2weapons_sword:sword:sword_wind";

fn bank() -> (Fsb5, Vec<u8>) {
    let bytes = aa_pak::Pak::global().read(BANK).unwrap();
    let fsb = Fsb5::parse(&bytes).unwrap();
    assert_eq!(
        (bytes.len(), fsb.version, fsb.codec, fsb.subsounds.len()),
        (44_192, 1, Codec::Celt, 1)
    );
    let sub = &fsb.subsounds[0];
    assert_eq!(
        (sub.frequency, sub.channels, sub.samples, sub.loop_points),
        (44_100, 1, 116_224, Some((0, 116_003)))
    );
    assert_eq!(sub.name.as_deref(), Some("sword_2h_wind_crit"));
    assert_eq!(
        u32::from_le_bytes(bytes[28..32].try_into().unwrap()),
        0x8000_0010
    );
    (fsb, bytes)
}

fn errors(actual: &[i16], reference: &[i16]) -> (i32, f64, f64) {
    assert_eq!(actual.len(), reference.len());
    let (mut max, mut noise, mut signal) = (0, 0.0, 0.0);
    for (&a, &b) in actual.iter().zip(reference) {
        let delta = i32::from(a) - i32::from(b);
        max = max.max(delta.abs());
        noise += f64::from(delta).powi(2);
        signal += f64::from(b).powi(2);
    }
    (
        max,
        (noise / actual.len() as f64).sqrt(),
        10.0 * (signal / noise).log10(),
    )
}

#[test]
fn celt_rejects_unsupported_container_and_bitstream_versions() {
    for (container, bitstream, valid) in [
        (1u32, 0x8000_0010u32, true),
        (0, 0x8000_0010, false),
        (2, 0x8000_0010, false),
        (1, 0x8000_0009, false),
        (1, 0, false),
        (1, 0x8000_0011, false),
    ] {
        let mut bytes = vec![0u8; 60];
        bytes[..4].copy_from_slice(b"FSB5");
        bytes[4..8].copy_from_slice(&container.to_le_bytes());
        bytes[24..28].copy_from_slice(&12u32.to_le_bytes());
        bytes[28..32].copy_from_slice(&bitstream.to_le_bytes());
        assert_eq!(
            Fsb5::parse(&bytes).is_ok(),
            valid,
            "container={container} bitstream={bitstream:#x}"
        );
    }
}

#[test]
#[ignore = "needs the game pak and AA_AUDIO_CELT_GOLDEN generated by the original CPU oracle"]
fn original_celt_matches_executed_native() {
    let (fsb, bytes) = bank();
    let pcm = decode(&fsb, &bytes, 0).expect("the original CELT subsound must decode");
    assert_eq!(
        (pcm.rate, pcm.channels, pcm.frames(), pcm.loop_points),
        (44_100, 1, 116_224, Some((0, 116_003)))
    );
    let reference = std::fs::read(
        std::env::var_os("AA_AUDIO_CELT_GOLDEN")
            .expect("set AA_AUDIO_CELT_GOLDEN to the original CPU oracle's .s16le output"),
    )
    .unwrap();
    assert_eq!(reference.len(), 232_448);
    let reference: Vec<i16> = reference
        .as_chunks::<2>()
        .0
        .iter()
        .map(|b| i16::from_le_bytes(*b))
        .collect();
    let (max, rms, snr) = errors(&pcm.samples, &reference);
    let mut rows = String::from("packet\tmax_error_lsb\trms_error_lsb\tsnr_db\n");
    for (i, (actual, native)) in pcm
        .samples
        .as_chunks::<512>()
        .0
        .iter()
        .zip(reference.as_chunks::<512>().0)
        .enumerate()
    {
        let (m, r, s) = errors(actual, native);
        rows.push_str(&format!("{i}\t{m}\t{r:.12}\t{s:.9}\n"));
    }
    if let Some(dir) = std::env::var_os("AA_AUDIO_CELT_EVIDENCE") {
        let dir = PathBuf::from(dir);
        std::fs::create_dir_all(&dir).unwrap();
        std::fs::write(
            dir.join("actual.s16le"),
            pcm.samples
                .iter()
                .flat_map(|s| s.to_le_bytes())
                .collect::<Vec<_>>(),
        )
        .unwrap();
        std::fs::write(dir.join("actual.wav"), pcm.to_wav()).unwrap();
        std::fs::write(dir.join("native-comparison.tsv"), rows).unwrap();
    }
    eprintln!(
        "original CELT: packets=227 rate={} channels={} frames={} loops={:?} max_error_lsb={max} rms_error_lsb={rms:.12} snr_db={snr:.9} rms={}",
        pcm.rate,
        pcm.channels,
        pcm.frames(),
        pcm.loop_points,
        pcm.rms()
    );
    assert!(pcm.rms() > 0.17 && pcm.rms() < 0.18);
    // Same legacy algorithm; permit only bounded x87/SSE/table rounding, never gain/lag fitting.
    assert!(
        max <= 2 && rms <= 0.1 && snr >= 95.0,
        "native error: max={max}, RMS={rms}, SNR={snr}"
    );
    assert_eq!(
        decode(&fsb, &bytes, 0).unwrap().samples,
        pcm.samples,
        "fresh decoder state must reproduce the complete stream"
    );
}

#[test]
#[ignore = "needs the game pak; CPU only"]
fn original_celt_fev_uses_critical_twohand_and_miss_gates() {
    let event = Library::global().event(EVENT).unwrap();
    let ev = event.event();
    assert_eq!(
        (ev.flags, ev.flags2, ev.mode, ev.category.as_str()),
        (8, 0x80000, 0x04080010, "master/weapon")
    );
    for (critical, twohand, miss, selected, audible) in [
        (1.0, 1.0, 0.0, true, true),
        (0.0, 1.0, 0.0, false, false),
        (1.0, 0.0, 0.0, true, false),
        (1.0, 1.0, 1.0, true, false),
    ] {
        let values = initial_values(
            ev,
            Some(1.0),
            &[
                ("critical".into(), critical),
                ("twohand".into(), twohand),
                ("miss".into(), miss),
            ],
        );
        assert_eq!(active_instances(ev, &values).contains(&(6, 0)), selected);
        assert_eq!(selected && layer_gain(ev, &values, 6) > 0.99, audible);
        let parts = plan(&event, &values, &mut PickState::default(), &mut Rng::new(3));
        let part = parts.iter().find(|p| p.layer == 6);
        assert_eq!(part.is_some(), selected);
        if let Some(part) = part {
            assert_eq!(
                (part.bank, part.index, part.looping, part.length_ms),
                (54, 0, false, 2630)
            );
            assert_eq!(part.name, "weapons2/sword_2h/sword_2h_wind_crit.wav");
        }
    }
}

#[test]
#[ignore = "needs the game pak; CPU benchmark, no audio device"]
fn original_celt_cpu_decode_cost() {
    let (fsb, bytes) = bank();
    let start = Instant::now();
    let first = std::hint::black_box(decode(&fsb, &bytes, 0).unwrap());
    let cold = start.elapsed().as_secs_f64() * 1000.0;
    let mut times = Vec::with_capacity(100);
    for _ in 0..100 {
        let start = Instant::now();
        let pcm = std::hint::black_box(decode(&fsb, &bytes, 0).unwrap());
        times.push(start.elapsed().as_secs_f64() * 1000.0);
        assert_eq!(pcm.frames(), 116_224);
    }
    times.sort_by(f64::total_cmp);
    eprintln!(
        "CELT CPU {}: cold_mode_state_and_decode_ms={cold:.6} warm_fresh_state_n=100 median_ms={:.6} p95_ms={:.6} max_ms={:.6} audio_s={:.9} pcm_bytes={} stereo_cache_bytes={}",
        if cfg!(debug_assertions) {
            "dev"
        } else {
            "release"
        },
        times[49],
        times[94],
        times[99],
        first.seconds(),
        first.bytes(),
        first.frames() * 8
    );
}
