#[test]
fn executed_full_native_quotes() {
    let rows = [
        (50000, 100, 13700, 4546, 100, false, 112280),
        (50000, 50, 13700, 4546, 117, false, 102118),
        (50000, 350, 13700, 4546, 130, false, 308464),
        (50000, 100, 13700, 4546, -1, false, -1123),
        (50000, 100, 10100, 2567, 100, false, 75927),
        (50000, 50, 10100, 2567, 117, false, 59585),
        (50000, 350, 10100, 2567, 130, false, 261205),
        (50000, 100, 10100, 2567, -1, false, -759),
        (50000, 100, 27000, 2876, 100, true, 13),
        (50000, 50, 27000, 2876, 117, true, 12),
        (50000, 350, 27000, 2876, 130, true, 33),
        (50000, 100, 27000, 2876, -1, true, 0),
    ];
    for (refund, refund_multiplier, profit, profit_ratio, received_ratio, coin, expected) in rows {
        let got = quote_known_bundle(KnownBundleQuote {
            refund,
            refund_multiplier,
            profit,
            profit_ratio,
            received_ratio,
            npc_ratio: 100.0,
            coin_divisor: coin.then_some(10000),
        });
        assert_eq!(
            if coin {
                got.coin_amount.unwrap()
            } else {
                got.refund
            },
            expected
        );
    }
}
