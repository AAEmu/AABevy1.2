#[test]
fn discriminates_pc24_and_preserves_invalid_cvtt() {
    assert_eq!(
        native_round(extended_product(
            210075,
            &[100.0, 0.01, extended_product(90, &[0.01])]
        )),
        189067
    );
    assert_eq!(native_round(f32::NAN), i32::MIN);
    assert_eq!(native_round(f32::INFINITY), i32::MIN);
    let input = KnownBundleQuote {
        refund: 100,
        refund_multiplier: 100,
        profit: 0,
        profit_ratio: 0,
        received_ratio: 100,
        npc_ratio: 100.0,
        coin_divisor: Some(0),
    };
    assert_eq!(quote_known_bundle(input).coin_amount, Some(i32::MIN));
    assert_eq!(extended_product(1, &[f32::from_bits(1)]).to_bits(), 1);
}
