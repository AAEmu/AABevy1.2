/// Add a stub for every known method missing from `methods`.
pub(crate) fn add_stubs(lua: &Lua, methods: &Table, kind: &str) -> mlua::Result<()> {
    for &name in KNOWN_METHODS {
        if methods.raw_get::<mlua::Value>(name)?.is_nil() {
            let key = format!("{kind}:{name}");
            methods.raw_set(
                name,
                lua.create_function(move |lua, _: MultiValue| {
                    let mut u = ui(lua);
                    let n = u.stub_calls.entry(key.clone()).or_insert(0);
                    if *n == 0 {
                        bevy::log::debug!("aa-ui: stub {key}");
                    }
                    *n += 1;
                    Ok(())
                })?,
            )?;
        }
    }
    Ok(())
}

fn stub(lua: &Lua, key: String) -> mlua::Result<mlua::Function> {
    lua.create_function(move |lua, _: MultiValue| {
        let mut u = ui(lua);
        let n = u.stub_calls.entry(key.clone()).or_insert(0);
        if *n == 0 {
            bevy::log::debug!("aa-ui: stub {key}");
        }
        *n += 1;
        Ok(())
    })
}

/// Make `methods` exactly the native class's method set: unimplemented ones become stubs, and
/// natives the class does not have are removed (scripts test for methods: `if w.SetEscEvent`).
/// Classes the reference does not list keep our natives plus stubs for every known name.
pub(crate) fn finalize(lua: &Lua, methods: &Table, class: &str) -> mlua::Result<()> {
    let Some(list) = methods_of(class) else {
        return add_stubs(lua, methods, class);
    };
    for &name in list {
        if methods.raw_get::<mlua::Value>(name)?.is_nil() {
            methods.raw_set(name, stub(lua, format!("{class}:{name}"))?)?;
        }
    }
    let extra: Vec<String> = methods
        .pairs::<String, mlua::Value>()
        .filter_map(|kv| kv.ok().map(|(k, _)| k))
        .filter(|k| !list.contains(&k.as_str()))
        .collect();
    for k in extra {
        methods.raw_set(k, mlua::Value::Nil)?;
    }
    Ok(())
}
